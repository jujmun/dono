#!/usr/bin/env node
/**
 * Sync the app/convex legal registry from dono-brain/legal/live-terms/.
 *
 * live-terms is the only public handoff: stripped Markdown/HTML/PDF + manifest.
 * Do not regenerate from suites/v3.0/public here — that path publishes internal
 * approval / solicitor-review material (see legal/publication-handoff/).
 *
 * Usage: node scripts/sync-legal-live-terms.mjs
 *        npm run legal:render
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const liveTermsRoot = path.join(root, "dono-brain/legal/live-terms");

/** Registry order — Student Campaign Terms intentionally absent (CR-00). */
const DOCUMENT_IDS = [
  "terms_of_service",
  "society_campaign_terms",
  "donor_terms",
  "community_guidelines",
  "privacy",
  "cookie",
  "refund_dispute",
  "verification",
  "complaints",
];

const FORBIDDEN = [
  "Solicitor review outstanding",
  "This block is unsigned",
  "prepared for approval and is not approved",
  "ENGINEERING_IMPLEMENTATION_CHECKLIST",
];

function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

const manifestPath = path.join(liveTermsRoot, "manifest.json");
if (!fs.existsSync(manifestPath)) {
  fail(`Missing live-terms manifest at ${manifestPath}`);
}

const handoff = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
if (!handoff.version || !handoff.documents) {
  fail("live-terms manifest missing version or documents");
}

const registryManifest = {
  version: handoff.version,
  versionDate: handoff.versionDate ?? null,
  effectiveDate: handoff.effectiveDate ?? null,
  source: "dono-brain/legal/live-terms",
  documents: {},
};
const bodies = {};

for (const id of DOCUMENT_IDS) {
  const entry = handoff.documents[id];
  if (!entry) fail(`live-terms manifest missing document "${id}"`);

  const mdRel = entry.markdownPath;
  const htmlRel = entry.htmlPath;
  const pdfRel = entry.pdfPath;
  if (!mdRel || !htmlRel || !pdfRel) {
    fail(`live-terms entry "${id}" missing markdown/html/pdf paths`);
  }

  const mdPath = path.join(liveTermsRoot, mdRel);
  const htmlPath = path.join(liveTermsRoot, htmlRel);
  const pdfPath = path.join(liveTermsRoot, pdfRel);
  for (const p of [mdPath, htmlPath, pdfPath]) {
    if (!fs.existsSync(p)) fail(`Missing artifact for ${id}: ${p}`);
  }

  const mdBuf = fs.readFileSync(mdPath);
  const htmlBuf = fs.readFileSync(htmlPath);
  const pdfBuf = fs.readFileSync(pdfPath);
  const markdownHash = sha256(mdBuf);
  const htmlHash = sha256(htmlBuf);
  const pdfHash = sha256(pdfBuf);

  if (entry.markdownHash && entry.markdownHash !== markdownHash) {
    fail(
      `Hash mismatch ${id} markdown: file=${markdownHash} manifest=${entry.markdownHash}`,
    );
  }
  if (entry.htmlHash && entry.htmlHash !== htmlHash) {
    fail(`Hash mismatch ${id} html: file=${htmlHash} manifest=${entry.htmlHash}`);
  }
  if (entry.pdfHash && entry.pdfHash !== pdfHash) {
    fail(`Hash mismatch ${id} pdf: file=${pdfHash} manifest=${entry.pdfHash}`);
  }

  const body = mdBuf.toString("utf8");
  for (const phrase of FORBIDDEN) {
    if (body.includes(phrase) || htmlBuf.toString("utf8").includes(phrase)) {
      fail(`Forbidden phrase in live-terms ${id}: "${phrase}"`);
    }
  }

  bodies[id] = body;
  registryManifest.documents[id] = {
    id,
    title: entry.title,
    version: entry.version ?? handoff.version,
    effectiveDate: entry.effectiveDate ?? handoff.effectiveDate ?? null,
    markdownPath: mdRel,
    htmlPath: htmlRel,
    pdfPath: pdfRel,
    // sourceHash = public Markdown hash (what in-product LegalMarkdownBody shows)
    sourceHash: markdownHash,
    htmlHash,
    pdfHash,
  };
}

function genTs(manifest, bodyMap) {
  return `// AUTO-GENERATED by scripts/sync-legal-live-terms.mjs — do not edit.
// Source: dono-brain/legal/live-terms (stripped public handoff).
export const LIVE_LEGAL_VERSION = ${JSON.stringify(manifest.version)} as const;
export const LIVE_LEGAL_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;
export const LIVE_LEGAL_BODIES: Record<string, string> = ${JSON.stringify(bodyMap, null, 2)};
`;
}

const ts = genTs(registryManifest, bodies);
const libOut = path.join(root, "lib/legal/artifacts/generated.ts");
const convexOut = path.join(root, "convex/lib/legalArtifacts/generated.ts");
fs.mkdirSync(path.dirname(libOut), { recursive: true });
fs.mkdirSync(path.dirname(convexOut), { recursive: true });
fs.writeFileSync(libOut, ts);
fs.writeFileSync(convexOut, ts);

console.log(
  `Synced ${DOCUMENT_IDS.length} docs from live-terms v${registryManifest.version} → lib + convex generated modules`,
);
